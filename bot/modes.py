def is_valid_mode(mode: str) -> bool:
    return mode in MODES


def get_mode(mode: str) -> Mode:
    """Возвращает режим по имени; неизвестное имя — режим по умолчанию."""
    return MODES.get(mode, MODES[DEFAULT_MODE])


def get_system_prompt(mode: str) -> str:
    """Собирает system-промпт: общие правила + правила режима."""
    return f"{COMMON_RULES}\n{get_mode(mode).prompt}"


def modes_help() -> str:
    """Список режимов для сообщений пользователю."""
    return "\n".join(f"/mode {m.name} — {m.title}: {m.description}" for m in MODES.values())
